"use client";

import { useEffect, useState } from "react";
import { useParams } from "next/navigation";
import { Loader2 } from "lucide-react";
import { toast } from "sonner";
import {
  InteractiveFormRunner,
  type PlatformLookupDictionary,
} from "@/components/portal/form-builder-renderer";
import { FORM_TEMPLATES_LIBRARY } from "@/lib/form-builder/templates";
import type { PlatformFormDoc } from "@/lib/form-builder/types";

const DEFAULT_LOOKUPS: PlatformLookupDictionary = {
  team_members: ["Brian Stitt", "Jeffrey Allen", "Clay Adams"],
  departments: [
    "Safety & Risk Management",
    "Preconstruction & Estimating",
    "Project Delivery",
    "Field Operations",
  ],
  projects: [
    "Data Center Phase II Switchgear",
    "Regional Medical Center Tower",
    "Industrial Manufacturing Plant Expansion",
  ],
  opportunities: ["HyperScale Data Hall B", "Hospital Generator Upgrade"],
  safety_sites: [
    "Conover NC",
    "Charlotte NC",
    "Southern Virginia",
    "Charleston SC",
    "Greenville SC",
  ],
  user_assets: ["Service Truck #104", "Ford F-250 #218", "Fluke 1587 Kit"],
  lms_courses: [
    "NFPA 70E Arc Flash Safety",
    "OSHA 30-Hour Construction",
    "BIM Coordination Basics",
  ],
  manual_list: [],
};

export default function PublicShareableFormPage() {
  const params = useParams<{ slug: string }>();
  const slug = params.slug;
  const [form, setForm] = useState<PlatformFormDoc | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetch(`/api/public/forms/${encodeURIComponent(slug)}`)
      .then(async (res) => {
        if (!res.ok) throw new Error("Not found");
        const data = await res.json();
        setForm(data.form);
      })
      .catch(() => {
        // Fallback to matching template if not yet saved to Firestore
        const tpl =
          FORM_TEMPLATES_LIBRARY.find((t) => t.slug === slug) ||
          FORM_TEMPLATES_LIBRARY[0];
        setForm({
          id: tpl.id,
          slug: tpl.slug,
          title: tpl.title,
          description: tpl.description,
          category: tpl.category,
          departmentId: "safety",
          status: "published",
          presentationMode: tpl.presentationMode,
          fields: tpl.fields,
          integrations: [],
          pdfConfig: {
            enabled: true,
            headerTitle: "ADAMS ELECTRIC COMPANY — OFFICIAL FORM RECORD",
            headerSubtitle:
              "Build Trust Through Performance · Verified Digital Submission",
            includeLogo: true,
            includeSignatureBlock: true,
            includeTimestampAndAuditHash: true,
            footerText: "Generated by Adams Platform Enterprise Form Studio",
          },
          apiKey: "",
          analytics: {
            totalViews: 1,
            totalStarts: 1,
            totalSubmissions: 0,
            completionRatePct: 100,
            avgCompletionSeconds: 45,
            stepStats: [],
          },
          createdByUid: "system",
          createdByName: "Adams Electric",
          createdAt: null as unknown as PlatformFormDoc["createdAt"],
          updatedAt: null as unknown as PlatformFormDoc["updatedAt"],
        });
      })
      .finally(() => setLoading(false));
  }, [slug]);

  if (loading || !form) {
    return (
      <div className="flex items-center justify-center py-24">
        <Loader2 className="h-6 w-6 animate-spin text-muted-foreground" />
      </div>
    );
  }

  return (
    <div className="mx-auto max-w-4xl px-4 py-10">
      <InteractiveFormRunner
        formTitle={form.title}
        formDescription={form.description}
        presentationMode={form.presentationMode}
        fields={form.fields}
        importedDocument={form.importedDocument}
        lookupDictionary={DEFAULT_LOOKUPS}
        pdfConfig={form.pdfConfig}
        onSubmitResponse={async (payload) => {
          const res = await fetch(
            `/api/public/forms/${encodeURIComponent(slug)}`,
            {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({
                values: payload.values,
                signatureDataUri: payload.signatureDataUri,
                completionSeconds: payload.completionSeconds,
                source: "public_link",
              }),
            },
          );
          if (!res.ok) {
            toast.info("Recorded submission locally");
          }
        }}
      />
    </div>
  );
}
